from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(); errs=[]
    pg=b.new_page(viewport={'width':420,'height':900},device_scale_factor=2)
    pg.on('pageerror',lambda e: errs.append('ERR '+str(e)))
    pg.on('console',lambda m: errs.append('CONSOLE '+m.text) if m.type=='error' else None)
    pg.goto('file:///home/claude/scapp/test.html'); pg.wait_for_timeout(1600)
    pg.screenshot(path='p1-inicio.png',full_page=True)
    pg.click('nav.bot button[data-v="estudar"]'); pg.wait_for_timeout(500)
    pg.click('#modulos details:nth-child(13) summary'); pg.wait_for_timeout(400)
    pg.screenshot(path='p2-modulo.png',full_page=True)
    pg.click('#modulos details:nth-child(13) .sub'); pg.wait_for_timeout(700)
    pg.screenshot(path='p3-questao.png',full_page=True)
    pg.click('#alts .alt:nth-child(2)'); pg.wait_for_timeout(200); pg.click('#b-conf'); pg.wait_for_timeout(900)
    pg.screenshot(path='p4-correcao.png',full_page=True)
    pg.click('nav.bot button[data-v="simulado"]'); pg.wait_for_timeout(400)
    pg.screenshot(path='p5-simulado.png',full_page=True)
    pg.click('nav.bot button[data-v="progresso"]'); pg.wait_for_timeout(400)
    pg.screenshot(path='p6-progresso.png',full_page=True)
    print('largura:',pg.evaluate("[document.documentElement.scrollWidth,innerWidth]"))
    pg2=b.new_page(viewport={'width':1100,'height':900},color_scheme='dark')
    pg2.on('pageerror',lambda e: errs.append('ERR2 '+str(e)))
    pg2.goto('file:///home/claude/scapp/test.html'); pg2.wait_for_timeout(1200)
    pg2.click('#b-simulado5'); pg2.wait_for_timeout(900)
    pg2.screenshot(path='p7-dark.png',full_page=True)
    print('erros:',errs if errs else 'nenhum')
    b.close()

def render(i):
    spec = M[i][0]
    src, name = spec.split(':', 1)
    if src == 'ph': return ph(name), PH % name
    if src == 'tb': return tb(name), TB % name
    if src == 'lu': return lu(name), LU % name
    if src == 'hi': return hi(name), HI % ('outline', name)
    if src == 'cu': return custom.get(name, 'm-' + i.replace('.', '-')), 'custom.py:' + name
    if src == 'bi': return bio(name), BIOPATH[name]
    raise KeyError(spec)


BIOPATH = {}
def prep_bio(force=False):
    items = []
    for k, (n, o) in BIO.items():
        g = glob.glob(BI + '*/*/*/' + n + '.svg')
        BIOPATH[k] = g[0]
        items.append((k, g[0][len(BI):], o))
    if force or not os.path.exists(BIO_CACHE) or any(k not in json.load(open(BIO_CACHE)) for k in BIO):
        bio_convert(items)


if __name__ == '__main__':
    prep_bio('--bio' in sys.argv)
    os.makedirs(OUT, exist_ok=True)
    for i in M:
        s, _ = render(i)
        open(f'{OUT}/{i}.svg', 'w').write(wrap(s))
